function getCurrentLang(){
  return localStorage.getItem('agrostar_lang') || 'en';
}

// t(key) — for text built in JavaScript (fetch-then-render card titles,
// buttons inside template literals, etc.) where data-i18n can't reach
// because the element doesn't exist until after a fetch() resolves.
// Falls back to English, then to the raw key, so a missing translation
// never breaks the page.
function t(key){
  const dict = TRANSLATIONS[getCurrentLang()] || TRANSLATIONS.en;
  return dict[key] || TRANSLATIONS.en[key] || key;
}

function setLang(lang){
  localStorage.setItem('agrostar_lang', lang);
  applyTranslations();
  document.dispatchEvent(new CustomEvent('agrostar:langchange', { detail: { lang } }));
}

function applyTranslations(){
  const lang = getCurrentLang();
  const dict = TRANSLATIONS[lang] || TRANSLATIONS.en;
  document.querySelectorAll('[data-i18n]').forEach(function(el){
    const key = el.getAttribute('data-i18n');
    if (dict[key]) el.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(function(el){
    const key = el.getAttribute('data-i18n-placeholder');
    if (dict[key]) el.setAttribute('placeholder', dict[key]);
  });
  document.documentElement.setAttribute('lang', lang === 'or' ? 'or' : lang);

  // Keep any per-page language <select> (e.g. AASHA's, quiz's) visually in
  // sync if present, without forcing pages that don't have one to error.
  document.querySelectorAll('.lang-sync-select').forEach(function(sel){
    sel.value = lang;
  });
}

// Any <select class="lang-sync-select"> anywhere in the app (AASHA's picker,
// the quiz's picker, etc.) drives the SAME global language — so choosing
// Hindi on the AASHA page also switches the bottom nav, page headers, and
// every other translated element app-wide, not just that one page.
document.addEventListener('change', function(e){
  if (e.target && e.target.classList && e.target.classList.contains('lang-sync-select')) {
    setLang(e.target.value);
  }
});

document.addEventListener('DOMContentLoaded', applyTranslations);
